let day = 1;
switch(day){
    case 1 : console.log('Monday');
    break;
    case 2 : console.log('Tue');
    break;
    case 3 : console.log('Wednes');
    break;
    case 4 : console.log('Thurs');
    break;
    case 5 : console.log('Fri');
    break;
    case 6 : console.log('Satur');
    break;
    case 7 : console.log('Sun');
    break;

    default: console.log("Invalid day");

}